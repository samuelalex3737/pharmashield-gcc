"""Regenerates deck/speaker_script.md from the speaker notes in deck/notebooklm_source_pack.md."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
pack = (ROOT / "deck" / "notebooklm_source_pack.md").read_text(encoding="utf-8")
slides = re.split(r"\n## (Slide \d - .*)\n", pack)
out = ["# Speaker Script - PharmaShield GCC [GENAI]", "",
       "Timed script for the 10-minute presentation (about 80 seconds per slide, 9 minutes 20 seconds in total, 40 seconds buffer). The text is identical to the speaker notes in deck/notebooklm_source_pack.md (regenerated by pipeline/builders/build_speaker_script.py so the two never drift apart). Speakers follow the master plan roster; replace \"Member N\" with names once confirmed (open item F18: ask the professor whether everyone must speak).", "",
       "Delivery rules:",
       "- Say the numbers exactly as written.",
       "- Pause after each headline.",
       "- Point at the figure when you say its number.",
       "- Hand over by naming the next speaker's topic.", ""]
speakers = {1: "Member 1", 2: "Member 2A (first half) and Member 2B (from \"The second lesson was names\")", 3: "Member 3", 4: "Member 4A",
            5: "Member 4B", 6: "Member 5", 7: "Member 1"}
handover = {1: "Hand over: \"Member 2 will show you where the data comes from.\"", 2: "Hand over: \"Member 3 will turn this evidence into a decision.\"",
            3: "Hand over: \"Member 4A will show how we predict the delays behind these scores.\"", 4: "Hand over: \"Member 4B will show what we learn from documents.\"",
            5: "Hand over: \"Member 5 will show who stays in control, live.\"", 6: "Hand over: \"Member 1 will close with the pilot and our ask.\"",
            7: "Close: \"Thank you. We welcome your questions.\""}
clock = 0
for i in range(1, len(slides), 2):
    title, body = slides[i], slides[i + 1]
    n = int(title.split()[1])
    notes = re.search(r"\*\*Speaker notes \(about 80 seconds\) \[GENAI\]\*\*\n(.*?)\n\n", body, re.S).group(1).strip()
    words = len(notes.split())
    start, clock = clock, clock + 80
    out += [f"## {title}", "", f"- Speaker: {speakers[n]}",
            f"- Time window: {start // 60}:{start % 60:02d} to {clock // 60}:{clock % 60:02d} (script length {words} words, about {round(words / 2.4)} seconds at 145 words a minute)",
            "", notes, "", handover[n], ""]
out += ["## Rehearsal checklist", "",
        "- [ ] Two timed full run-throughs on Mon 16 Nov (target 9:20 or less).",
        "- [ ] Demo laptop: app open on the Scorecard page, the backup video on the desktop.",
        "- [ ] Every [GENAI] element circled in red dashed outline; footnote on each slide.",
        "- [ ] Every number checked against docs/number_trace.md.",
        "- [ ] Q&A owners assigned (deck/qa_prep.md)."]
(ROOT / "deck" / "speaker_script.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("speaker script words per slide:", re.findall(r"script length (\d+) words", "\n".join(out)))
